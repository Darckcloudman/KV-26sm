"""Модуль преобразования единиц измерения."""


def kw_to_mw(kw: float) -> float:
    """Преобразовать киловатты в мегаватты."""
    return kw / 1000.0


def kwh_to_gwh(kwh: float) -> float:
    """Преобразовать киловатт-часы в гигаватт-часы."""
    return kwh / 1_000_000.0


def rpm_to_hz(rpm: float) -> float:
    """Преобразовать обороты в минуту в герцы."""
    return rpm / 60.0


def ms2_to_g(ms2: float) -> float:
    """Преобразовать м/с² в g (ускорение свободного падения)."""
    return ms2 / 9.80665
